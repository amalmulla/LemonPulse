    ax.legend()
    ax.grid(axis='y', linestyle='--', alpha=0.7)
    plt.tight_layout()

    # 5. Return as Base64 for the UI
    buf = io.BytesIO()
    fig.savefig(buf, format='png', bbox_inches='tight', dpi=120, transparent=True)
    plt.close(fig)
    return base64.b64encode(buf.getvalue()).decode()

